#!/usr/bin/env node
'use strict';
/**
 * write-ship-chain-doc.js — regenerates the ship-chain block in AGENTS.md from
 * scripts/ship-chain.json, so the human documentation cannot drift from what
 * SHIP-GYM.ps1 actually runs (S2-F1).
 *
 * The block is delimited by HTML comments. Everything between them is generated;
 * everything outside them is hand-written and never touched.
 *
 * Run: node scripts/write-ship-chain-doc.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const START = '<!-- SHIP-CHAIN:START — generated by scripts/write-ship-chain-doc.js, do not edit by hand -->';
const END = '<!-- SHIP-CHAIN:END -->';

const chain = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'ship-chain.json'), 'utf8'));

function render() {
  const L = [];
  L.push(START);
  L.push('');
  L.push('`SHIP-GYM.ps1` is the shipping authority and it reads `scripts/ship-chain.json`.');
  L.push('This section is generated from that same file — edit the JSON, then run');
  L.push('`node scripts/write-ship-chain-doc.js`. `scripts/verify-ship-chain.js` fails the');
  L.push('build if the two ever disagree.');
  L.push('');
  L.push('**Normal route — one command, runs everything below plus every gate, and pushes nothing if a gate fails:**');
  L.push('');
  L.push('```powershell');
  L.push('powershell -NoProfile -ExecutionPolicy Bypass -File C:\\Projects\\pattayagym\\SHIP-GYM.ps1');
  L.push('```');
  L.push('');
  L.push('Add `-DryRun` to build and gate without touching git.');
  L.push('');
  L.push(`### Build — ${chain.build.length} steps, in this order`);
  L.push('');
  L.push('```cmd');
  L.push('npm install');
  for (const s of chain.build) L.push(`node ${s.script}`);
  L.push('```');
  L.push('');
  const buildWhy = chain.build.filter(s => s.why);
  if (buildWhy.length) {
    L.push('Order that matters:');
    L.push('');
    for (const s of buildWhy) L.push(`- \`${s.script}\` — ${s.why}`);
    L.push('');
  }
  L.push(`### Gates — ${chain.gates.length}, all must pass or nothing ships`);
  L.push('');
  L.push('```cmd');
  for (const g of chain.gates) L.push(g.npm ? `npm run ${g.npm}` : `node ${g.script}`);
  L.push('```');
  L.push('');
  const gateWhy = chain.gates.filter(g => g.why);
  if (gateWhy.length) {
    L.push('Why each hard gate exists:');
    L.push('');
    for (const g of gateWhy) L.push(`- \`${g.npm ? 'npm run ' + g.npm : g.script}\` — ${g.why}`);
    L.push('');
  }
  if (chain.manual && chain.manual.length) {
    L.push('### Run deliberately, not on every ship');
    L.push('');
    for (const m of chain.manual) {
      L.push(`- \`${m.script}\` — ${m.why}`);
      if (m.how) { L.push(''); L.push('  ```powershell'); L.push('  ' + m.how); L.push('  ```'); L.push(''); }
    }
  }
  L.push(END);
  return L.join('\n');
}

module.exports = { render, START, END, chain };

/* Only rewrite AGENTS.md when run directly - scripts/verify-ship-chain.js
   requires this module to compare, and must not have a side effect. */
if (require.main !== module) return;

const file = path.join(ROOT, 'AGENTS.md');
let md = fs.readFileSync(file, 'utf8');
const block = render();
const i = md.indexOf(START), j = md.indexOf(END);

if (i >= 0 && j > i) {
  md = md.slice(0, i) + block + md.slice(j + END.length);
} else {
  throw new Error(`AGENTS.md has no ${START} / ${END} block. Add the two markers around the chain section first.`);
}
fs.writeFileSync(file, md, 'utf8');
console.log(`ship-chain doc: AGENTS.md regenerated from scripts/ship-chain.json (${chain.build.length} build steps, ${chain.gates.length} gates).`);
